CREATE TABLE IF NOT EXISTS place_resources (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    place_id BIGINT UNSIGNED NOT NULL,
    area_feature_id BIGINT UNSIGNED NULL,
    resource_type VARCHAR(64) NOT NULL,
    resource_subtype VARCHAR(64) NULL,
    name VARCHAR(160) NULL,
    latitude DECIMAL(10,7) NULL,
    longitude DECIMAL(10,7) NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'unknown',
    fee_status VARCHAR(32) NOT NULL DEFAULT 'unknown',
    fee_description VARCHAR(255) NULL,
    hours_text VARCHAR(255) NULL,
    access_type VARCHAR(64) NULL,
    access_notes TEXT NULL,
    notes TEXT NULL,
    source_provider VARCHAR(160) NULL,
    source_external_id VARCHAR(255) NULL,
    source_url TEXT NULL,
    source_updated_at DATETIME NULL,
    verified_at DATETIME NULL,
    created_by BIGINT UNSIGNED NULL,
    updated_by BIGINT UNSIGNED NULL,
    sort_order INT NOT NULL DEFAULT 0,
    is_active TINYINT(1) NOT NULL DEFAULT 1,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_place_resources_place (place_id, is_active, sort_order, id),
    KEY idx_place_resources_area (place_id, area_feature_id, is_active),
    KEY idx_place_resources_type (place_id, resource_type, is_active),
    KEY idx_place_resources_coordinates (latitude, longitude)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
