CREATE TABLE IF NOT EXISTS resources (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    resource_type VARCHAR(64) NOT NULL,
    name VARCHAR(160) NOT NULL,
    latitude DECIMAL(10,7) NOT NULL,
    longitude DECIMAL(10,7) NOT NULL,
    street_address VARCHAR(255) NULL,
    city VARCHAR(120) NULL,
    state_region VARCHAR(120) NULL,
    postal_code VARCHAR(32) NULL,
    country_code CHAR(2) NULL,
    phone VARCHAR(64) NULL,
    website_url TEXT NULL,
    hours_text VARCHAR(255) NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'unknown',
    notes TEXT NULL,
    source_provider VARCHAR(160) NULL,
    source_external_id VARCHAR(255) NULL,
    source_url TEXT NULL,
    source_updated_at DATETIME NULL,
    verified_at DATETIME NULL,
    created_by BIGINT UNSIGNED NULL,
    updated_by BIGINT UNSIGNED NULL,
    is_active TINYINT(1) NOT NULL DEFAULT 1,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    KEY idx_resources_type (resource_type, is_active),
    KEY idx_resources_status (status, is_active),
    KEY idx_resources_coordinates (latitude, longitude)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS resource_services (
    id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
    resource_id BIGINT UNSIGNED NOT NULL,
    service_type VARCHAR(64) NOT NULL,
    status VARCHAR(32) NOT NULL DEFAULT 'unknown',
    fee_status VARCHAR(32) NOT NULL DEFAULT 'unknown',
    fee_description VARCHAR(255) NULL,
    access_notes TEXT NULL,
    notes TEXT NULL,
    sort_order INT NOT NULL DEFAULT 0,
    is_active TINYINT(1) NOT NULL DEFAULT 1,
    created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    PRIMARY KEY (id),
    UNIQUE KEY uq_resource_services_type (resource_id, service_type),
    KEY idx_resource_services_resource (resource_id, is_active, sort_order, id),
    KEY idx_resource_services_type (service_type, is_active)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
