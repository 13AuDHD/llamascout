const assert = require('node:assert/strict');
const prefs = require('../../js/map-preferences.js');

const map = new Map();
const storage = {getItem: key => map.get(key) ?? null, setItem: (key, value) => map.set(key,value)};
assert.equal(prefs.readView(storage),null);
assert.deepEqual(prefs.readFilters(storage),[]);
prefs.saveView(storage,{lat:37.3,lng:-107.4,zoom:12});
assert.deepEqual(prefs.readView(storage),{lat:37.3,lng:-107.4,zoom:12});
prefs.saveView(storage,{lat:40,lng:253,zoom:10});
assert.deepEqual(prefs.readView(storage),{lat:40,lng:-107,zoom:10});
prefs.saveView(storage,{lat:95,lng:0,zoom:10});
assert.equal(prefs.readView(storage).lat,40);
map.set('llama-map-view-v1','{"lat":37,"lng":-107,"zoom":99}');
assert.equal(prefs.readView(storage),null);
map.set('llama-map-view-v1','broken JSON');
assert.equal(prefs.readView(storage),null);
prefs.saveFilters(storage,['water','laundry','water','invalid','__proto__']);
assert.deepEqual(prefs.readFilters(storage),['water','laundry']);
assert.deepEqual([...prefs.serviceTypes(['water'])],['potable_water','water_fill']);
const resource = {marker_service_type:'fuel',services:[{service_type:'fuel'},{service_type:'potable_water'},{service_type:'shower'}]};
assert.equal(prefs.matchingService(resource,[]),null);
assert.equal(prefs.matchingService(resource,['water']),'potable_water');
assert.equal(prefs.matchingService(resource,['water','fuel']),'fuel');
assert.equal(prefs.matchingService(resource,['laundry']),null);
assert.equal(prefs.matchingService({services:[{service_type:'water_fill'}]},['water']),'water_fill');
assert.equal(prefs.matchingService({services:[{service_type:'recycling'}]},['other']),'recycling');
assert.equal(prefs.readView(null),null);
assert.deepEqual(prefs.readFilters(null),[]);
assert.doesNotThrow(()=>prefs.saveView(null,{lat:1,lng:2,zoom:3}));
assert.doesNotThrow(()=>prefs.saveFilters(null,['water']));
console.log('PASS: saved viewport, safe storage fallback, service groups and multi-service marker selection.');
